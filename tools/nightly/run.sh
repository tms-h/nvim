#!/usr/bin/env bash
# tools/nightly/run.sh: the nightly Neovim config job (nvim-nightly.timer, 04:00).
# A headless claude fixes every friction note logged since the last fixed one, then does a
# behaviour-keeping cleanup of tonight's area (tools/nightly/areas.txt, one line per night).
# It works in a throwaway worktree on branch nightly/<day> from origin/main; this script then
# runs tests/check.sh itself. Pass: squash-merge to main as one commit, push, fast-forward
# ~/.config/nvim (only if that checkout is clean and on main). Fail: push the branch, leave main.
#   tools/nightly/run.sh            the real run
#   tools/nightly/run.sh --dry-run  same, but never merges or pushes, and keeps the marker
# Pause:   systemctl --user stop nvim-nightly.timer   (or: touch ~/.local/state/nvim/nightly/paused)
# Output:  ~/.local/state/nvim/nightly/latest.md (3 lines), history.md (newest on top),
#          logs/<day>.log and logs/<day>.claude.jsonl
set -euo pipefail
REPO=${NVIM_REPO:-$HOME/.config/nvim}
STATE=${XDG_STATE_HOME:-$HOME/.local/state}/nvim/nightly
FRICTION=${XDG_STATE_HOME:-$HOME/.local/state}/nvim/usage/friction.md
MAX_RUNTIME=${MAX_RUNTIME:-90m}
DAY=$(date +%F)
DRY=; [[ ${1:-} == --dry-run ]] && DRY=1
mkdir -p "$STATE/logs"

# The final fast-forward rewrites this file in ~/.config/nvim; run from a copy so bash never reads a changed script.
if [[ -z ${NIGHTLY_COPY:-} ]]; then
  cp "$0" "$STATE/run-copy.sh"
  NIGHTLY_COPY=1 exec bash "$STATE/run-copy.sh" "$@"
fi

[[ -e $STATE/paused ]] && { echo "paused ($STATE/paused exists)"; exit 0; }
LOG=$STATE/logs/$DAY${DRY:+-dry}.log
JSONL=$STATE/logs/$DAY${DRY:+-dry}.claude.jsonl
RESULT=$STATE/logs/$DAY${DRY:+-dry}.result.json
exec > >(tee -a "$LOG") 2>&1
exec 9>"$STATE/lock"; flock -n 9 || { echo "another nightly run is going"; exit 0; }
echo "=== $(date '+%F %T') nvim nightly${DRY:+ (dry run)}"

BRANCH=nightly/$DAY${DRY:+-dry}
WT=$HOME/.cache/nvim-nightly/wt-$DAY${DRY:+-dry}
export NVNEXT=/tmp/nvnightly            # short: the test socket path must stay under 108 chars
export TMUX_SOCK=nvnightly-$$

report() {  # $1 fixed line, $2 cleaned line, $3 flagged/failed line, $4 urgency
  local body="Fixed: $1
Cleaned: $2
Flagged: $3"
  printf '# Neovim nightly %s\n%s\n' "$(date '+%F %H:%M')" "$body" >"$STATE/latest.md"
  { cat "$STATE/latest.md"; echo; cat "$STATE/history.md" 2>/dev/null || true; } >"$STATE/history.md.new"
  mv "$STATE/history.md.new" "$STATE/history.md"
  command -v notify-send >/dev/null && notify-send -u "${4:-normal}" -a Neovim "Neovim nightly" "$body" || true
}
cleanup() {
  cd /
  [[ -d $WT ]] && git -C "$REPO" worktree remove --force "$WT" 2>/dev/null || true
  git -C "$REPO" worktree prune
  tmux -L "$TMUX_SOCK" kill-server 2>/dev/null || true
}
fail() {  # keep the branch for a look in the morning
  echo "FAIL: $1"
  if [[ -d $WT ]] && [[ $(git -C "$WT" rev-list --count "$BASE..HEAD" 2>/dev/null || echo 0) -gt 0 ]]; then
    [[ -z $DRY ]] && git -C "$WT" push -q -f origin "HEAD:refs/heads/$BRANCH" 2>/dev/null || true
    kept=" Branch $BRANCH kept."
  fi
  report "${FIXED_LINE:-nothing merged}" "${CLEANED_LINE:-nothing merged}" "FAILED: $1.${kept:-} Log: $LOG" critical
  exit 1
}
trap cleanup EXIT

# 1. Fresh base: origin/main in a throwaway worktree (the live checkout is never edited mid-run).
git -C "$REPO" fetch -q origin main || fail "git fetch"
rm -rf "$WT"; git -C "$REPO" worktree prune
git -C "$REPO" branch -D "$BRANCH" 2>/dev/null || true
git -C "$REPO" worktree add -q -b "$BRANCH" "$WT" origin/main || fail "worktree add"
BASE=$(git -C "$WT" rev-parse HEAD)
# lua/surface.lua is generated by the omarchy theme hook and gitignored; the config needs it.
[[ -f $REPO/lua/surface.lua ]] && cp "$REPO/lua/surface.lua" "$WT/lua/surface.lua"

# 2. New notes: every friction line after the last fixed one (marker = that line, verbatim).
NOTES=$(python3 -I - "$FRICTION" "$STATE/last-fixed" <<'PY'
import sys, pathlib
fr, mk = map(pathlib.Path, sys.argv[1:])
lines = [l for l in (fr.read_text().splitlines() if fr.exists() else []) if l.startswith("- 20")]
mark = mk.read_text().strip() if mk.exists() else ""
if mark in lines:                       # normal case: everything after the marker line
    new = lines[len(lines) - lines[::-1].index(mark):]
else:                                   # marker line edited or gone: fall back to its timestamp
    ts = mark[2:18]
    new = [l for l in lines if l[2:18] > ts]
print("\n".join(new))
PY
)
N_NOTES=$(grep -c '^- 20' <<<"$NOTES" || true)
NUMBERED=$(awk 'NF { printf "N%d %s\n", ++n, $0 }' <<<"$NOTES")
echo "--- $N_NOTES new friction notes"; echo "$NUMBERED"

# 3. Tonight's cleanup area (rotation index in $STATE/area-index).
mapfile -t AREAS < <(grep -v '^#' "$WT/tools/nightly/areas.txt" | grep .)
IDX=$(( $(cat "$STATE/area-index" 2>/dev/null || echo 0) % ${#AREAS[@]} ))
AREA=${AREAS[$IDX]}
echo "--- cleanup area $IDX: $AREA"

# 4. Claude.
PROMPT="$(cat "$WT/tools/nightly/prompt.md")

## Tonight
- Today: $DAY. Worktree (your cwd, branch $BRANCH, based on origin/main $BASE): $WT
- Live config checkout, read-only for you: $REPO
- Test env: NVNEXT=$NVNEXT TMUX_SOCK=$TMUX_SOCK (already exported; use TMUX_SOCK=\$TMUX_SOCK-<n> for parallel runs)
- Result file to write at the end: $RESULT
- Cleanup area tonight: $AREA
- New friction notes ($N_NOTES), oldest first:
${NUMBERED:-(none tonight: do the cleanup pass only)}"
cd "$WT"
echo "--- claude (log: $JSONL)"
rm -f "$RESULT"
timeout "$MAX_RUNTIME" nice -n 19 claude -p "$PROMPT" --permission-mode auto -n "nvim-nightly-$DAY${DRY:+-dry}" \
  --output-format stream-json --verbose >"$JSONL" 2>&1 \
  || echo "WARN: claude exited $? (timeout or usage limit?); checking what it left"
jq -r 'select(.type=="result") | .result' "$JSONL" 2>/dev/null | tail -30 || true

# 5. Verify: result file, committed work only, nothing in tools/nightly, tests pass.
[[ -s $RESULT ]] && jq -e . "$RESULT" >/dev/null 2>&1 || fail "claude left no valid result file ($RESULT)"
FIXED_LINE=$(jq -r '[.fixed[]? | .summary] | if length == 0 then "no new notes" else "\(length): " + join("; ") end' "$RESULT")
CLEANED_LINE=$(jq -r --arg a "$AREA" '[.cleaned[]?] | if length == 0 then "nothing in \($a)" else "\($a): " + join("; ") end' "$RESULT")
FLAGGED_LINE=$(jq -r '[(.flagged[]? | "\(.id) \(.why)")] | if length == 0 then "none" else join("; ") end' "$RESULT")
git status --porcelain | grep -q . && { git status --short; fail "uncommitted changes left in the worktree"; }
git diff --name-only "$BASE" HEAD | grep -q '^tools/nightly/' && fail "the run edited tools/nightly (the job itself)"
N_COMMITS=$(git rev-list --count "$BASE..HEAD")
echo "--- $N_COMMITS commits on $BRANCH"; git log --oneline "$BASE..HEAD"
echo "--- tests/check.sh"
CHECK=$(tests/check.sh 2>&1) || true
echo "$CHECK" | grep -E '^(FAIL|pass |elapsed)' || true
grep -q '^pass [1-9][0-9]* fail 0 ' <<<"$CHECK" || fail "tests/check.sh: $(grep -m3 '^FAIL' <<<"$CHECK" | tr '\n' ' ')$(grep '^pass ' <<<"$CHECK")"
PASS_LINE=$(grep '^pass ' <<<"$CHECK")

# 6. Advance the marker past every handed-in note the result reports (fixed or flagged), in order.
advance_marker() {
  NOTES="$NOTES" python3 -I - "$RESULT" "$STATE/last-fixed" <<'PY'
import json, os, sys, pathlib
res = json.load(open(sys.argv[1])); mk = pathlib.Path(sys.argv[2])
done = {e.get("id") for k in ("fixed", "flagged") for e in res.get(k, [])}
last = None
for i, line in enumerate(l for l in os.environ["NOTES"].splitlines() if l.strip()):
    if f"N{i + 1}" in done: last = line
    else: break
if last: mk.write_text(last + "\n"); print("marker ->", last)
PY
}

if [[ $N_COMMITS -eq 0 ]]; then
  [[ -z $DRY ]] && { advance_marker; echo $(( IDX + 1 )) >"$STATE/area-index"; }
  report "$FIXED_LINE" "$CLEANED_LINE" "$FLAGGED_LINE. No changes; tests $PASS_LINE"
  exit 0
fi
if [[ -n $DRY ]]; then
  git diff "$BASE" HEAD >"$STATE/logs/$DAY-dry.patch"
  report "$FIXED_LINE" "$CLEANED_LINE" "$FLAGGED_LINE. DRY RUN, not merged; tests $PASS_LINE"
  exit 0
fi

# 7. Squash-merge: one commit on main, the per-fix commits listed in its body; push; ff the live checkout.
git push -q -f origin "HEAD:refs/heads/$BRANCH" || true   # keep the per-fix history on GitHub
BODY=$(git log --reverse --format='- %s (%h)' "$BASE..HEAD")
git reset -q --soft "$BASE"
git commit -q -m "Nightly config pass $DAY" -m "Friction notes: $FIXED_LINE
Cleanup: $CLEANED_LINE
Flagged: $FLAGGED_LINE
Per-fix commits (branch $BRANCH):
$BODY
Tests: $PASS_LINE" -m "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"
if ! git push -q origin HEAD:main; then   # main moved (a push from the Mac): rebase once, retest
  git pull -q --rebase origin main || fail "rebase onto a newer main"
  tests/check.sh 2>&1 | grep -q '^pass [1-9][0-9]* fail 0 ' || fail "tests after rebasing onto a newer main"
  git push -q origin HEAD:main || fail "push to main"
fi
SHA=$(git rev-parse --short HEAD)
echo "pushed $SHA to origin/main"
advance_marker
echo $(( IDX + 1 )) >"$STATE/area-index"
FF="main fast-forwarded"
if [[ $(git -C "$REPO" branch --show-current) == main ]]; then
  git -C "$REPO" merge -q --ff-only origin/main 2>/dev/null || FF="~/.config/nvim NOT fast-forwarded (local changes; run git pull there)"
else
  FF="~/.config/nvim not on main; left alone"
fi
echo "$FF"
cd / && git -C "$REPO" worktree remove --force "$WT" && git -C "$REPO" branch -q -D "$BRANCH" || true   # per-fix history stays on origin/$BRANCH
report "$FIXED_LINE" "$CLEANED_LINE" "$FLAGGED_LINE. Merged $SHA ($PASS_LINE); $FF"
echo "=== done $(date '+%T')"
